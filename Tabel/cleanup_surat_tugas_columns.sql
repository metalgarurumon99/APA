ALTER TABLE public.surat_tugas ADD COLUMN IF NOT EXISTS jumlah_responden INT DEFAULT 1;
ALTER TABLE public.surat_tugas ADD COLUMN IF NOT EXISTS status TEXT DEFAULT 'menunggu';
ALTER TABLE public.surat_tugas ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ DEFAULT now();
ALTER TABLE public.surat_tugas ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ DEFAULT now();

-- LANGKAH 2: Migrasi / Backfill data dari kolom duplikat ke kolom utama (jika ada data)
DO $$
BEGIN
    -- Backfill tanggal_surat dari tgl_surat
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='surat_tugas' AND column_name='tgl_surat') THEN
        UPDATE public.surat_tugas SET tanggal_surat = COALESCE(tanggal_surat, tgl_surat) WHERE tanggal_surat IS NULL AND tgl_surat IS NOT NULL;
    END IF;

    -- Backfill tanggal_berangkat dari tgl_mulai
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='surat_tugas' AND column_name='tgl_mulai') THEN
        UPDATE public.surat_tugas SET tanggal_berangkat = COALESCE(tanggal_berangkat, tgl_mulai) WHERE tanggal_berangkat IS NULL AND tgl_mulai IS NOT NULL;
    END IF;

    -- Backfill tanggal_kembali dari tgl_selesai
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='surat_tugas' AND column_name='tgl_selesai') THEN
        UPDATE public.surat_tugas SET tanggal_kembali = COALESCE(tanggal_kembali, tgl_selesai) WHERE tanggal_kembali IS NULL AND tgl_selesai IS NOT NULL;
    END IF;

    -- Backfill waktu_pelaksanaan_text dari waktu_pelaksanaan
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='surat_tugas' AND column_name='waktu_pelaksanaan') THEN
        UPDATE public.surat_tugas SET waktu_pelaksanaan_text = COALESCE(waktu_pelaksanaan_text, waktu_pelaksanaan) WHERE waktu_pelaksanaan_text IS NULL AND waktu_pelaksanaan IS NOT NULL;
    END IF;

    -- Backfill tujuan dari tempat_tujuan
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='surat_tugas' AND column_name='tempat_tujuan') THEN
        UPDATE public.surat_tugas SET tujuan = COALESCE(tujuan, tempat_tujuan) WHERE tujuan IS NULL AND tempat_tujuan IS NOT NULL;
    END IF;

    -- Backfill pegawai_nip dari pegawai_nip_list
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='surat_tugas' AND column_name='pegawai_nip_list') THEN
        UPDATE public.surat_tugas SET pegawai_nip = COALESCE(pegawai_nip, pegawai_nip_list) WHERE (pegawai_nip IS NULL OR pegawai_nip = '[]'::jsonb) AND pegawai_nip_list IS NOT NULL;
    END IF;

    -- Backfill menimbang_custom dari menimbang
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='surat_tugas' AND column_name='menimbang') THEN
        UPDATE public.surat_tugas SET menimbang_custom = COALESCE(menimbang_custom, menimbang) WHERE menimbang_custom IS NULL AND menimbang IS NOT NULL;
    END IF;

    -- Backfill pembebanan dari pok_id
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='surat_tugas' AND column_name='pok_id') THEN
        UPDATE public.surat_tugas SET pembebanan = COALESCE(pembebanan, pok_id) WHERE pembebanan IS NULL AND pok_id IS NOT NULL;
    END IF;

    -- Backfill tipe dari tipe_surat
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='surat_tugas' AND column_name='tipe_surat') THEN
        UPDATE public.surat_tugas SET tipe = COALESCE(tipe, tipe_surat) WHERE tipe IS NULL AND tipe_surat IS NOT NULL;
    END IF;

    -- Backfill user_id dari created_by
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='surat_tugas' AND column_name='created_by') THEN
        UPDATE public.surat_tugas SET user_id = COALESCE(user_id, created_by) WHERE user_id IS NULL AND created_by IS NOT NULL;
    END IF;
END $$;

