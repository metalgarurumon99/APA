ALTER TABLE public.surat_tugas ADD COLUMN IF NOT EXISTS tanggal_kembali TEXT;
ALTER TABLE public.surat_tugas ADD COLUMN IF NOT EXISTS waktu_pelaksanaan_text TEXT;
ALTER TABLE public.surat_tugas ADD COLUMN IF NOT EXISTS pegawai_nip JSONB DEFAULT '[]'::jsonb;
ALTER TABLE public.surat_tugas ADD COLUMN IF NOT EXISTS pegawai_list JSONB DEFAULT '[]'::jsonb;
ALTER TABLE public.surat_tugas ADD COLUMN IF NOT EXISTS bertugas_sebagai JSONB DEFAULT '[]'::jsonb;
