-- 1. AKTIFKAN EKSTENSI KRIPTOGRAFI (PGCRYPTO)
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 2. TABEL 1: USERS
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    must_change_password BOOLEAN DEFAULT TRUE NOT NULL,
    full_name TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    last_login TIMESTAMPTZ,
    role TEXT DEFAULT 'user' NOT NULL,
    roles JSONB DEFAULT '["user"]'::jsonb NOT NULL,
    notifikasi_last_read_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_users_username ON public.users(username);

-- 3. TABEL 2: DATA_PEGAWAI
-- Menggunakan kolom username untuk relasi ke tabel users, dan pegawai_nip sebagai kolom referensi utama ke tabel-tabel riwayat
CREATE TABLE IF NOT EXISTS public.data_pegawai (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE REFERENCES public.users(username) ON UPDATE CASCADE ON DELETE SET NULL,
    pegawai_nip TEXT UNIQUE NOT NULL,
    karpeg TEXT,
    ttl TEXT,
    jk TEXT,
    unit_kerja TEXT DEFAULT 'BPS Kabupaten Raja Ampat',
    pendidikan_terakhir TEXT,
    foto_url TEXT,
    status_kepegawaian TEXT DEFAULT 'aktif',
    tanggal_pensiun TEXT,
    keterangan_status TEXT,
    nip_lama TEXT,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_data_pegawai_nip ON public.data_pegawai(pegawai_nip);
CREATE INDEX IF NOT EXISTS idx_data_pegawai_username ON public.data_pegawai(username);

-- 4. TABEL 3: RIWAYAT_JABATAN
-- NIP menjadi kolom referensi ke data_pegawai(pegawai_nip)
CREATE TABLE IF NOT EXISTS public.riwayat_jabatan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pegawai_nip TEXT NOT NULL REFERENCES public.data_pegawai(pegawai_nip) ON UPDATE CASCADE ON DELETE CASCADE,
    jabatan TEXT NOT NULL,
    tmt TEXT,
    tmt_ikut_pak TEXT,
    jenis TEXT DEFAULT 'utama',
    tmt_selesai TEXT,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_riwayat_jabatan_nip ON public.riwayat_jabatan(pegawai_nip);

-- 5. TABEL 4: RIWAYAT_PANGKAT_GOLONGAN
-- NIP menjadi kolom referensi ke data_pegawai(pegawai_nip)
CREATE TABLE IF NOT EXISTS public.riwayat_pangkat_golongan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pegawai_nip TEXT NOT NULL REFERENCES public.data_pegawai(pegawai_nip) ON UPDATE CASCADE ON DELETE CASCADE,
    pangkat TEXT NOT NULL,
    golongan TEXT NOT NULL,
    tmt TEXT,
    tmt_ikut_pak TEXT,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_riwayat_pangkat_nip ON public.riwayat_pangkat_golongan(pegawai_nip);

-- 6. TABEL 5: RIWAYAT_ANGKA_KREDIT
-- NIP menjadi kolom referensi ke data_pegawai(pegawai_nip)
CREATE TABLE IF NOT EXISTS public.riwayat_angka_kredit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pegawai_nip TEXT NOT NULL REFERENCES public.data_pegawai(pegawai_nip) ON UPDATE CASCADE ON DELETE CASCADE,
    angka_kredit NUMERIC(10, 3) NOT NULL DEFAULT 0,
    tmt TEXT,
    periode_tahun INT,
    periode_bulan_awal INT,
    periode_bulan_akhir INT,
    periode_label TEXT,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_riwayat_ak_nip ON public.riwayat_angka_kredit(pegawai_nip);

-- 7. TABEL 6: RIWAYAT_GELAR
-- NIP menjadi kolom referensi ke data_pegawai(pegawai_nip)
CREATE TABLE IF NOT EXISTS public.riwayat_gelar (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pegawai_nip TEXT NOT NULL REFERENCES public.data_pegawai(pegawai_nip) ON UPDATE CASCADE ON DELETE CASCADE,
    gelar_depan TEXT,
    gelar_belakang TEXT,
    tmt TEXT,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_riwayat_gelar_nip ON public.riwayat_gelar(pegawai_nip);

