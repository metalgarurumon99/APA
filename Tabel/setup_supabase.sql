-- 9. FUNGSI RPC: AUTENTIKASI LOGIN & GANTI PASSWORD
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.login_user(
    p_username TEXT,
    p_password TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
    v_user RECORD;
    v_pegawai RECORD;
BEGIN
    p_username := trim(p_username);

    SELECT id, username, password_hash, must_change_password, full_name, role, roles
    INTO v_user
    FROM public.users
    WHERE lower(username) = lower(p_username);

    IF NOT FOUND THEN
        RETURN jsonb_build_object('success', false, 'message', 'Username atau password salah');
    END IF;

    IF v_user.password_hash = extensions.crypt(p_password, v_user.password_hash) THEN
        UPDATE public.users SET last_login = now() WHERE id = v_user.id;

        -- Ambil NIP yang bersesuaian di data_pegawai
        SELECT pegawai_nip INTO v_pegawai FROM public.data_pegawai WHERE lower(username) = lower(v_user.username);

        RETURN jsonb_build_object(
            'success', true,
            'user', jsonb_build_object(
                'id', v_user.id,
                'username', v_user.username,
                'full_name', v_user.full_name,
                'role', v_user.role,
                'roles', v_user.roles,
                'must_change_password', v_user.must_change_password,
                'pegawai_nip', v_pegawai.pegawai_nip
            )
        );
    ELSE
        RETURN jsonb_build_object('success', false, 'message', 'Username atau password salah');
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.change_user_password(
    p_username TEXT,
    p_old_password TEXT,
    p_new_password TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
    v_user RECORD;
BEGIN
    p_username := trim(p_username);

    IF length(p_new_password) < 6 OR p_new_password !~ '[A-Za-z]' OR p_new_password !~ '[0-9]' THEN
        RETURN jsonb_build_object('success', false, 'message', 'Password minimal 6 karakter dan harus kombinasi huruf serta angka');
    END IF;

    SELECT id, password_hash INTO v_user FROM public.users WHERE lower(username) = lower(p_username);

    IF NOT FOUND THEN
        RETURN jsonb_build_object('success', false, 'message', 'Pengguna tidak ditemukan');
    END IF;

    IF v_user.password_hash != extensions.crypt(p_old_password, v_user.password_hash) THEN
        RETURN jsonb_build_object('success', false, 'message', 'Password lama tidak sesuai');
    END IF;

    UPDATE public.users
    SET password_hash = extensions.crypt(p_new_password, extensions.gen_salt('bf', 10)),
        must_change_password = FALSE,
        last_login = now()
    WHERE id = v_user.id;

    RETURN jsonb_build_object('success', true, 'message', 'Password berhasil diperbarui');
END;
$$;

-- 10. FUNGSI RPC: AMBIL SELURUH DATA PROFIL PEGAWAI BERDASARKAN USERNAME
CREATE OR REPLACE FUNCTION public.get_pegawai_profile(p_username TEXT)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_user RECORD;
    v_pegawai RECORD;
    v_nip TEXT;
    v_jabatan JSONB;
    v_pangkat JSONB;
    v_angka_kredit JSONB;
    v_gelar JSONB;
BEGIN
    -- 1. Ambil data user
    SELECT id, username, full_name, role, roles, must_change_password
    INTO v_user
    FROM public.users
    WHERE lower(username) = lower(trim(p_username));

    IF NOT FOUND THEN
        RETURN jsonb_build_object('success', false, 'message', 'User tidak ditemukan');
    END IF;

    -- 2. Ambil data_pegawai berdasarkan username
    SELECT * INTO v_pegawai
    FROM public.data_pegawai
    WHERE lower(username) = lower(v_user.username);

    v_nip := v_pegawai.pegawai_nip;

    -- 3. Ambil riwayat berdasarkan pegawai_nip
    SELECT COALESCE(jsonb_agg(to_jsonb(j) ORDER BY j.id DESC), '[]'::jsonb)
    INTO v_jabatan
    FROM public.riwayat_jabatan j
    WHERE j.pegawai_nip = v_nip;

    SELECT COALESCE(jsonb_agg(to_jsonb(p) ORDER BY p.id DESC), '[]'::jsonb)
    INTO v_pangkat
    FROM public.riwayat_pangkat_golongan p
    WHERE p.pegawai_nip = v_nip;

    SELECT COALESCE(jsonb_agg(to_jsonb(a) ORDER BY a.periode_tahun DESC, a.periode_bulan_akhir DESC, a.id DESC), '[]'::jsonb)
    INTO v_angka_kredit
    FROM public.riwayat_angka_kredit a
    WHERE a.pegawai_nip = v_nip;

    SELECT COALESCE(jsonb_agg(to_jsonb(g) ORDER BY g.id DESC), '[]'::jsonb)
    INTO v_gelar
    FROM public.riwayat_gelar g
    WHERE g.pegawai_nip = v_nip;

    RETURN jsonb_build_object(
        'success', true,
        'user', to_jsonb(v_user),
        'data_pegawai', to_jsonb(v_pegawai),
        'riwayat_jabatan', v_jabatan,
        'riwayat_pangkat_golongan', v_pangkat,
        'riwayat_angka_kredit', v_angka_kredit,
        'riwayat_gelar', v_gelar
    );
END;
$$;

-- Berikan izin akses RPC
GRANT EXECUTE ON FUNCTION public.login_user(TEXT, TEXT) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.change_user_password(TEXT, TEXT, TEXT) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.get_pegawai_profile(TEXT) TO anon, authenticated;

